mark = float(input("Enter the mark: "))
if mark < 0:
    print ("Invalid")
if mark > 100:
    print ("Invalid")
if mark >=0 and mark <=39:
    print ("Not Achieved")
if mark >=40 and mark <=49:
    print ("Not Yet Competent")
if mark >=50 and mark <=69:
    print ("Competent")
if mark >=70 and mark <=79:
    print ("Highly Competent")
if mark >=80 and mark <=100:
    print ("Outstanding")

